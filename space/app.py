"""Side-by-side demo: the original DeepSeek-R1 1.5B vs the weight-edited copy.

Local:   python space/app.py            (models load on the first request)
Check:   python space/app.py --check    (builds the UI and exits; no model is loaded)
Space:   copy common.py next to this file; set WSP_EDIT_MODEL to the edited model's HF repo id.

Greedy decoding, max 4,096 new tokens, same prompt format as the evaluation (common.build_prompt_ids).
A "LOOP DETECTED" badge uses common.is_looping on the generated token ids, and that side stops there.
On a GPU with >= 10 GB both models stream at the same time; on smaller GPUs (the 6 GB RTX 4050) they
run in turn, left first, each moved onto the GPU only while it generates.
"""
from __future__ import annotations

import html
import os
import sys
import threading
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))          # on the Space, common.py sits next to app.py
sys.path.insert(1, str(HERE.parent))   # locally, it is in the project root
from common import BASE_MODEL, build_prompt_ids, is_looping  # noqa: E402

BASE_REVISION = "ad9f0ae0864d7fbcd1cd905e3c6c5b069cc8b562"   # pinned, as in RUNLOG.md
EDIT_MODEL = os.environ.get("WSP_EDIT_MODEL", str(HERE.parent / "work" / "edit"))
MAX_NEW = int(os.environ.get("WSP_MAX_NEW", "4096"))
LOOP_CHECK_EVERY = 64
LABELS = ("DeepSeek-R1 1.5B (original)", "After Claude's weight edit")
EXAMPLES = [   # practice problems (MATH train, checked not in MATH-500); never test-set problems
    "A bag contains 10 red marbles and 6 blue marbles. Three marbles are selected at random and without "
    "replacement. What is the probability that one marble is red and two are blue? Express your answer "
    "as a common fraction.",
    "If $\\mathbf{a}$ and $\\mathbf{b}$ are two unit vectors, with an angle of $\\frac{\\pi}{3}$ between them, then compute the volume of the parallelepiped generated by $\\mathbf{a},$ $\\mathbf{b} + \\mathbf{b} \\times \\mathbf{a},$ and $\\mathbf{b}.$",
]

_models: dict[str, object] = {}
_tok = None
_lock = threading.Lock()


def _load():
    """Load tokenizer and both models once (bf16). Returns (tok, models, parallel)."""
    global _tok
    import torch
    from transformers import AutoModelForCausalLM, AutoTokenizer
    with _lock:
        if not _models:
            _tok = AutoTokenizer.from_pretrained(BASE_MODEL, revision=BASE_REVISION)
            for key, name, rev in (("base", BASE_MODEL, BASE_REVISION), ("edit", EDIT_MODEL, None)):
                _models[key] = AutoModelForCausalLM.from_pretrained(
                    name, revision=rev, dtype=torch.bfloat16).eval()
            if parallel_ok():
                for m in _models.values():
                    m.to("cuda")
    return _tok, _models, parallel_ok()


def parallel_ok() -> bool:
    import torch
    return torch.cuda.is_available() and torch.cuda.get_device_properties(0).total_memory >= 10 * 2**30


class LoopStop:
    """Stopping criterion that checks the generated ids with common.is_looping."""

    def __init__(self, prompt_len: int, state: dict):
        self.prompt_len, self.state = prompt_len, state

    def __call__(self, input_ids, scores, **kw):
        gen = input_ids[0, self.prompt_len:]
        self.state["n"] = int(gen.shape[0])
        if self.state["n"] % LOOP_CHECK_EVERY == 0 and is_looping(gen.tolist()):
            self.state["loop"] = True
            return True
        return False


def _start(model, tok, prompt_ids, state):
    """Generate in a background thread; returns the text streamer."""
    import torch
    from transformers import StoppingCriteriaList, TextIteratorStreamer
    dev = "cuda" if torch.cuda.is_available() else "cpu"
    streamer = TextIteratorStreamer(tok, skip_prompt=True, skip_special_tokens=True)
    ids = torch.tensor([prompt_ids], device=dev)
    kw = dict(input_ids=ids, attention_mask=torch.ones_like(ids), max_new_tokens=MAX_NEW, do_sample=False,
              temperature=None, top_p=None, top_k=None, streamer=streamer,
              stopping_criteria=StoppingCriteriaList([LoopStop(len(prompt_ids), state)]))

    def run():
        try:
            with torch.inference_mode():
                model.generate(**kw)
        except Exception as e:   # surface errors in the pane instead of hanging the stream
            state["error"] = repr(e)
            streamer.on_finalized_text("", stream_end=True)
        finally:
            state["done"] = True

    threading.Thread(target=run, daemon=True).start()
    return streamer


def badge(state: dict, label: str, waiting: bool = False) -> str:
    if state.get("error"):
        text, bg, fg = f"ERROR: {state['error'][:80]}", "#EB3324", "#fff"
    elif waiting:
        text, bg, fg = "WAITING (runs after the left side on this GPU)", "#BDB8AD", "#111"
    elif state.get("loop"):
        text, bg, fg = f"↻ LOOP DETECTED at {state['n']:,} tokens, stopped", "#EB3324", "#fff"
    elif state.get("done"):
        capped = state.get("n", 0) >= MAX_NEW
        text = f"HIT THE {MAX_NEW:,}-TOKEN LIMIT" if capped else f"FINISHED IN {state.get('n', 0):,} TOKENS"
        bg, fg = ("#FFE08A", "#111") if capped else ("#22C55E", "#111")
    else:
        text, bg, fg = f"GENERATING · {state.get('n', 0):,} tokens", "#1F3BFF", "#fff"
    return (f"<div style='font-family:Impact,Arial Black,sans-serif;font-size:20px;letter-spacing:.5px'>"
            f"{html.escape(label.upper())}</div><span style='display:inline-block;margin-top:6px;"
            f"padding:4px 10px;border:3px solid #111;box-shadow:4px 4px 0 #111;background:{bg};color:{fg};"
            f"font-family:Consolas,monospace;font-weight:bold'>{html.escape(text)}</span>")


def compare(question: str):
    """Gradio generator: yields (left badge, left text, right badge, right text)."""
    question = (question or "").strip()
    if not question:
        yield badge({}, LABELS[0]), "", badge({}, LABELS[1]), ""
        return
    tok, models, parallel = _load()
    import torch
    prompt = build_prompt_ids(tok, {"question": question, "kind": "math"})
    st = [{"n": 0}, {"n": 0}]
    txt = ["", ""]
    keys = ("base", "edit")
    if parallel:
        streams = [_start(models[k], tok, prompt, s) for k, s in zip(keys, st)]
        its = [iter(s) for s in streams]
        live = [True, True]
        while any(live):
            for i in (0, 1):
                if live[i]:
                    try:
                        txt[i] += next(its[i])
                    except StopIteration:
                        live[i] = False
            yield badge(st[0], LABELS[0]), txt[0], badge(st[1], LABELS[1]), txt[1]
        return
    for i, k in enumerate(keys):   # in turn: one model on the GPU at a time
        m = models[k]
        if torch.cuda.is_available():
            m.to("cuda")
        last = 0.0
        for piece in _start(m, tok, prompt, st[i]):
            txt[i] += piece
            if time.time() - last > 0.1:
                last = time.time()
                yield (badge(st[0], LABELS[0]), txt[0],
                       badge(st[1], LABELS[1], waiting=(i == 0)), txt[1])
        while not st[i].get("done"):
            time.sleep(0.05)
        if torch.cuda.is_available():
            m.to("cpu")
            torch.cuda.empty_cache()
    yield badge(st[0], LABELS[0]), txt[0], badge(st[1], LABELS[1]), txt[1]


def build_ui():
    import gradio as gr
    with gr.Blocks(title="Same model, edited weights") as demo:
        gr.Markdown("# Same model. Same question.\nLeft: DeepSeek-R1-Distill-Qwen-1.5B as released. Right: the "
                    "same model after Claude edited a small share of its weights directly (no training). "
                    f"Greedy decoding, up to {MAX_NEW:,} new tokens; a side stops when it starts repeating "
                    "itself word for word.")
        q = gr.Textbox(label="Math question", lines=3, value=EXAMPLES[0])
        gr.Examples(EXAMPLES, inputs=q)
        go = gr.Button("Run both", variant="primary")
        with gr.Row():
            with gr.Column():
                b0 = gr.HTML(badge({}, LABELS[0]))
                t0 = gr.Textbox(show_label=False, lines=22, max_lines=22, autoscroll=True)
            with gr.Column():
                b1 = gr.HTML(badge({}, LABELS[1]))
                t1 = gr.Textbox(show_label=False, lines=22, max_lines=22, autoscroll=True)
        go.click(compare, inputs=q, outputs=[b0, t0, b1, t1])
    return demo


if __name__ == "__main__":
    ui = build_ui()
    if "--check" in sys.argv:
        print("UI built OK; edit model path:", EDIT_MODEL)
    else:
        ui.queue().launch(server_name="127.0.0.1", server_port=int(os.environ.get("PORT", "7860")))
